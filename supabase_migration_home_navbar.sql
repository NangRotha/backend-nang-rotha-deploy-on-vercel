-- Run once in Supabase SQL Editor. Home, About, and Navbar remain independent after seeding.
create table if not exists public.navbar (
  id bigint generated by default as identity primary key,
  brand_name text not null,
  logo_url text,
  home_label_km text not null default 'ទំព័រដើម',
  home_label_en text not null default 'Home',
  about_label_km text not null default 'អំពីខ្ញុំ',
  about_label_en text not null default 'About',
  projects_label_km text not null default 'គម្រោង',
  projects_label_en text not null default 'Projects',
  contact_label_km text not null default 'ទាក់ទង',
  contact_label_en text not null default 'Contact',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.home (
  id bigint generated by default as identity primary key,
  display_name text not null,
  role text,
  profile_image text,
  availability_text text,
  eyebrow text,
  headline text,
  description text,
  primary_button_text text,
  secondary_button_text text,
  tech_stack jsonb not null default '[]'::jsonb,
  metric_label text,
  metric_value text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.site_settings (
  id bigint generated by default as identity primary key,
  maintenance_enabled boolean not null default false,
  maintenance_title text not null default 'Portfolio is being improved',
  maintenance_message text not null default 'We are building something better. Please check back soon.',
  expected_back_at text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Seed each new table once from the current profile. Later updates never read from About.
insert into public.navbar (brand_name, logo_url)
